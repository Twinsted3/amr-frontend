// Reconstructed business registrations from biz/router.InitRouter.
// The original middleware, static site and metrics proxy are in the separate pseudocode listings.
package router

import (
	"CAS-Backend/biz/controller"
	"github.com/gin-gonic/gin"
)

func RegisterBusinessRoutes(r *gin.Engine) {
	api := r.Group("/cas/biz/v1")

	user := api.Group("/user")
	user.POST("/sign_in", controller.LoginHandler)
	user.GET("/sign_out")
	user.POST("/sign_up", controller.RegisterHandler)
	user.POST("/new")
	user.DELETE("/del")
	user.POST("/alter")
	user.GET("")

	usergroup := api.Group("/user_group")
	usergroup.POST("/new")
	usergroup.DELETE("/del")
	usergroup.POST("/alter")
	usergroup.GET("")

	task := api.Group("/task")
	task.POST("/new", controller.NewTaskHandler)
	task.DELETE("/del", controller.DeleteTaskHandler)
	task.POST("/alter", controller.UpdateTaskHandler)
	task.GET("", controller.GetAllTaskHandler)
	task.GET("/status1", controller.HuifuTaskHandler)
	task.GET("/status0", controller.GuaqiTaskHandler)
	task.POST("/exc", controller.ExcTaskHandler)
	task.GET("/status", controller.TaskStatusHandler)
	task.POST("/pause", controller.PauseNavigationHandler)
	task.POST("/resume", controller.ResumeNavigationHandler)
	task.POST("/cancel", controller.CancelNavigationHandler)
	task.GET("/auto/status", controller.GetAutoTaskScheduleStatusHandler)
	task.POST("/auto", controller.AutoTaskScheduleHandler)
	task.POST("/auto/stop", controller.StopAutoTaskScheduleHandler)

	taskchain := api.Group("/task-chain")
	taskchain.POST("/new", controller.NewTaskChainHandler)
	taskchain.DELETE("/del", controller.DeleteTaskChainHandler)
	taskchain.POST("/alter", controller.UpdateTaskChainHandler)
	taskchain.GET("", controller.GetAllTaskChainHandler)
	taskchain.POST("/exc", controller.ExcTaskChainHandler)
	taskchain.GET("/status", controller.TaskChainStatusHandler)
	taskchain.POST("/pause", controller.PauseTaskChainHandler)
	taskchain.POST("/resume", controller.ResumeTaskChainHandler)
	taskchain.POST("/cancel", controller.CancelTaskChainHandler)

	traffic := api.Group("/traffic")
	traffic.POST("/monitor-push", controller.MonitorTrafficPushHandler)

	vehicle := api.Group("/vehicle")
	vehicle.POST("/new", controller.NewVehHandler)
	vehicle.DELETE("/del", controller.DeleteVehHandler)
	vehicle.POST("/alter", controller.UpdateVehHandler)
	vehicle.GET("/", controller.GetAllVehHandler)
	vehicle.GET("/runtime/ws", controller.VehicleRuntimeWSHandler)
	vehicle.POST("/runtime-push", controller.VehicleRuntimePushHandler)

	control := api.Group("/control")
	control.POST("/forward", controller.Move_forword)
	control.POST("/take-control", controller.Qiangzhan)
	control.POST("/release-control", controller.Shifang)
	control.POST("/backward", controller.Move_back)
	control.POST("/left", controller.Turn_left)
	control.POST("/right", controller.Turn_right)
	control.POST("/lift", controller.Huocha_up)
	control.POST("/hcset", controller.Huocha_set)
	control.POST("/lower", controller.Huocha_down)
	control.POST("/guiling", controller.Guiling)
	control.POST("/relocation", controller.Chongdingwei)
	control.POST("/stop", controller.Ruanjiting)
	control.POST("/translate", controller.Pingdong)
	control.POST("/rotate", controller.Zhuandong)
	control.POST("/arcMove", controller.Yuanhuyundong)
	control.POST("/manurelocation", controller.ChongdingweiManu)

	mapGroup := api.Group("/map")
	mapGroup.POST("/new", controller.StartMap)
	mapGroup.POST("/stopnew", controller.StopMap)
	mapGroup.GET("/stream", controller.MapStream)
	mapGroup.POST("/del", controller.DeleteMapHandler)
	mapGroup.POST("/alter", controller.UpdateMapHandler)
	mapGroup.GET("/", controller.GetAllMapHandler)
	mapGroup.GET("/overview", controller.GetOverviewMapHandler)
	mapGroup.GET("/file", controller.GetMapHandler)
	mapGroup.POST("/push", controller.Jieshoutuisong)
	mapGroup.POST("/query", controller.QMapRHandler)
	mapGroup.POST("/save", controller.DownloadMapHandler)
	mapGroup.POST("/upload", controller.UploadMapHandler)
	mapGroup.POST("/load", controller.LoadMapHandler)
	mapGroup.POST("/uploadload", controller.UploadLoadMapHandler)
	mapGroup.POST("/list", controller.QMapHandler)
	mapGroup.POST("/delete", controller.DelVehMapHandler)
}
